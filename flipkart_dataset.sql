-- Calculate the month-over-month growth in sales for each "Market."

WITH monthly_sales AS (
    SELECT 
        market,
        DATE_FORMAT(order_date, '%Y-%m') AS order_month,
        SUM(Sales) AS total_sales
    FROM 
        flipkart
    GROUP BY 
        market, order_month
)
SELECT 
    market,
    order_month,
    total_sales,
    LAG(total_sales) OVER (PARTITION BY market ORDER BY order_month) AS previous_month_sales,
    ROUND(((total_sales - LAG(total_sales) OVER (PARTITION BY market ORDER BY order_month)) / 
    LAG(total_sales) OVER (PARTITION BY market ORDER BY order_month)) * 100, 2) AS month_over_month_growth
FROM 
    monthly_sales
ORDER BY 
    market, order_month;


